#define TARGETM_CUMARGS_ENTRY(NAME, SYM) { NAME, &SYM },
const struct target_cumargs_entry targetm_cumargs_registry[] = {
  TARGETM_CUMARGS_TABLES
  { NULL, NULL }
};
#undef TARGETM_CUMARGS_ENTRY

/* NULL, not the primary's table.  See target-regs.h for the argument at
   length: a default here compiles aarch64 arguments with i386's
   argument-passing state, in bounds and with no diagnostic.  */
const struct target_cumargs_desc *targetm_cumargs;

const struct target_cumargs_desc *
target_cumargs_for (const char *base)
{
  for (const struct target_cumargs_entry *e = targetm_cumargs_registry;
       e->name != NULL; e++)
    if (strcmp (e->name, base) == 0)
      return e->cumargs;
  return NULL;
}

/* The shared-code entry points.  Each is one indirection with a by-name check
   in front of it.

   THE CHECK IS NOT DEFENSIVE PROGRAMMING.  These are on the path every
   function compilation takes, and the state they guard against -- no target
   selected -- is reachable: `cc1' without `-ftarget-config=' has no base.
   Without the check the first `->init_args' is a null call, which arrives as
   a SIGSEGV at address 0 and reads as a miscompile rather than as "you did
   not select a target".  */
